'use client';

import { useState } from 'react';

import { FormAlert } from '@/components/shared/form-alert';
import { Button } from '@/components/ui/button';
import { errorMessage } from '@/lib/form-errors';

import { useEnableTwoFactor, useSetupTwoFactor } from '../mutations';

import { OtpField } from './otp-field';

/**
 * TOTP setup: start → scan QR (or type the key) → confirm a code → show backup codes ONCE.
 * Used on the account security page and the forced admin setup page.
 */
export function TwoFactorSetup({
  onEnabled,
  onDone,
}: {
  /** Called right after 2FA is turned on (before the backup codes are acknowledged). */
  onEnabled?: () => void;
  onDone?: () => void;
}) {
  const setup = useSetupTwoFactor();
  const enable = useEnableTwoFactor();
  const [code, setCode] = useState('');
  const [codeError, setCodeError] = useState<string | undefined>();
  const [acknowledged, setAcknowledged] = useState(false);

  if (enable.isSuccess) {
    const codes = enable.data.backupCodes;
    return (
      <div className="grid gap-4">
        <FormAlert tone="success" message="Two-factor authentication is on." />
        <div className="grid gap-2">
          <h3 className="font-medium">Save your backup codes</h3>
          <p className="text-muted-foreground text-sm">
            Each code can be used once if you lose access to your authenticator app. They won&apos;t
            be shown again.
          </p>
          <ul
            className="grid grid-cols-2 gap-2 rounded-md border p-4 font-mono text-sm"
            aria-label="Backup codes"
            data-testid="backup-codes"
          >
            {codes.map((c) => (
              <li key={c}>{c}</li>
            ))}
          </ul>
        </div>
        <label className="flex items-center gap-2 text-sm">
          <input
            type="checkbox"
            checked={acknowledged}
            onChange={(e) => {
              setAcknowledged(e.target.checked);
            }}
          />
          I have saved these codes somewhere safe
        </label>
        <div>
          <Button disabled={!acknowledged} onClick={onDone}>
            Done
          </Button>
        </div>
      </div>
    );
  }

  if (!setup.data) {
    return (
      <div className="grid gap-3">
        <FormAlert message={setup.isError ? errorMessage(setup.error) : undefined} />
        <p className="text-muted-foreground text-sm">
          Use an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password…) to
          generate sign-in codes.
        </p>
        <div>
          <Button
            onClick={() => {
              setup.mutate();
            }}
            disabled={setup.isPending}
          >
            {setup.isPending ? 'Preparing…' : 'Set up two-factor authentication'}
          </Button>
        </div>
      </div>
    );
  }

  async function confirm(event: React.SubmitEvent<HTMLFormElement>) {
    event.preventDefault();
    setCodeError(undefined);
    if (!/^\d{6}$/.test(code)) {
      setCodeError('Enter the 6-digit code.');
      return;
    }
    try {
      await enable.mutateAsync(code);
      onEnabled?.();
    } catch (error) {
      setCodeError(errorMessage(error));
      setCode('');
    }
  }

  return (
    <form
      onSubmit={(e) => void confirm(e)}
      noValidate
      className="grid gap-4"
      aria-label="Confirm two-factor setup"
    >
      <ol className="text-muted-foreground grid list-decimal gap-1 pl-5 text-sm">
        <li>Scan this QR code with your authenticator app.</li>
        <li>Enter the 6-digit code it shows.</li>
      </ol>
      {/* data: URL generated by our backend; allowed by img-src 'self' data: */}
      {/* eslint-disable-next-line @next/next/no-img-element -- data URL, nothing to optimise */}
      <img
        src={setup.data.qrCodeDataUrl}
        alt="QR code for your authenticator app"
        width={192}
        height={192}
        className="rounded-md border bg-white p-2"
      />
      <details className="text-sm">
        <summary className="cursor-pointer">Can&apos;t scan? Enter this key instead</summary>
        <code className="bg-muted mt-2 block rounded p-2 break-all" data-testid="totp-secret">
          {setup.data.secret}
        </code>
      </details>
      <FormAlert message={codeError} />
      <OtpField id="setup-code" value={code} onChange={setCode} autoFocus />
      <div>
        <Button type="submit" disabled={enable.isPending}>
          {enable.isPending ? 'Verifying…' : 'Turn on two-factor authentication'}
        </Button>
      </div>
    </form>
  );
}
